#!/bin/sh

set -euf

# Global variables for temporary files
user_hosts_file=""
blacklist_sources=""
whitelist_sources=""
blacklist_domains=""
whitelist_domains=""
final_hosts_file=""
previous_crontab=""
new_crontab=""
# tmp_domains is handled locally in process_domain_list
tmp_downloadFile=""

# Function to clean up temporary files
cleanup_temp_files() {
  debug_echo "Cleaning up temporary files..."
  rm -f "$user_hosts_file" \
    "$blacklist_sources" \
    "$whitelist_sources" \
    "$blacklist_domains" \
    "$whitelist_domains" \
    "$final_hosts_file" \
    "$previous_crontab" \
    "$new_crontab" \
    "$tmp_downloadFile" # Removed tmp_domains
}

# Trap EXIT, TERM, INT signals to run cleanup function
trap cleanup_temp_files EXIT TERM INT

VERSION="1.9.7"
RELEASE_DATE="29/jan/24"
PROJECT_URL="4st.li/hosty"
BLACKLIST_DEFAULT_SOURCE="https://4st.li/hosty/lists/blacklist.sources"
WHITELIST_DEFAULT_SOURCE="https://4st.li/hosty/lists/whitelist.sources"
BLOCK_IP="0.0.0.0"
INPUT_HOSTS="/etc/hosts"
OUTPUT_HOSTS="/etc/hosts"

# @getoptions
parser_definition() {
  setup REST help:usage -- "usage: hosty [-airduhv]" ''
  msg -- 'options:'
  flag AUTORUN -a --autorun -- "set up autorun with cronie"
  flag IGNORE_DEFAULT_SOURCES -i --ignore-default-sources -- "ignore default sources"
  flag RESTORE -r --restore -- "restore the hosts file"
  flag DEBUG -d --debug -- "run in debug mode"
  flag UNINSTALL -u --uninstall -- "uninstall hosty from the system"
  disp :usage -h --help
  disp VERSION -v --version
}
# @end

# @gengetoptions parser -i parser_definition parse
# Generated by getoptions (BEGIN)
# URL: https://github.com/ko1nksm/getoptions (v3.3.0)
AUTORUN=''
IGNORE_DEFAULT_SOURCES=''
RESTORE=''
DEBUG=''
UNINSTALL=''
REST=''
parse() {
  OPTIND=$(($# + 1))
  while OPTARG= && [ $# -gt 0 ]; do
    case $1 in
    --?*=*)
      OPTARG=$1
      shift
      eval 'set -- "${OPTARG%%\=*}" "${OPTARG#*\=}"' ${1+'"$@"'}
      ;;
    --no-* | --without-*) unset OPTARG ;;
    -[airduhv]?*)
      OPTARG=$1
      shift
      eval 'set -- "${OPTARG%"${OPTARG#??}"}" -"${OPTARG#??}"' ${1+'"$@"'}
      OPTARG=
      ;;
    esac
    case $1 in
    '-a' | '--autorun')
      [ "${OPTARG:-}" ] && OPTARG=${OPTARG#*\=} && set "noarg" "$1" && break
      eval '[ ${OPTARG+x} ] &&:' && OPTARG='1' || OPTARG=''
      AUTORUN="$OPTARG"
      ;;
    '-i' | '--ignore-default-sources')
      [ "${OPTARG:-}" ] && OPTARG=${OPTARG#*\=} && set "noarg" "$1" && break
      eval '[ ${OPTARG+x} ] &&:' && OPTARG='1' || OPTARG=''
      IGNORE_DEFAULT_SOURCES="$OPTARG"
      ;;
    '-r' | '--restore')
      [ "${OPTARG:-}" ] && OPTARG=${OPTARG#*\=} && set "noarg" "$1" && break
      eval '[ ${OPTARG+x} ] &&:' && OPTARG='1' || OPTARG=''
      RESTORE="$OPTARG"
      ;;
    '-d' | '--debug')
      [ "${OPTARG:-}" ] && OPTARG=${OPTARG#*\=} && set "noarg" "$1" && break
      eval '[ ${OPTARG+x} ] &&:' && OPTARG='1' || OPTARG=''
      DEBUG="$OPTARG"
      ;;
    '-u' | '--uninstall')
      [ "${OPTARG:-}" ] && OPTARG=${OPTARG#*\=} && set "noarg" "$1" && break
      eval '[ ${OPTARG+x} ] &&:' && OPTARG='1' || OPTARG=''
      UNINSTALL="$OPTARG"
      ;;
    '-h' | '--help')
      usage
      exit 0
      ;;
    '-v' | '--version')
      echo "${VERSION}"
      exit 0
      ;;
    --)
      shift
      while [ $# -gt 0 ]; do
        REST="${REST} \"\${$((OPTIND - $#))}\""
        shift
      done
      break
      ;;
    [-]?*)
      set "unknown" "$1"
      break
      ;;
    *)
      REST="${REST} \"\${$((OPTIND - $#))}\""
      ;;
    esac
    shift
  done
  [ $# -eq 0 ] && {
    OPTIND=1
    unset OPTARG
    return 0
  }
  case $1 in
  unknown) set "unrecognized option: $2" "$@" ;;
  noarg) set "does not allow an argument: $2" "$@" ;;
  required) set "requires an argument: $2" "$@" ;;
  pattern:*) set "does not match the pattern (${1#*:}): $2" "$@" ;;
  notcmd) set "not a command: $2" "$@" ;;
  *) set "validation error ($1): $2" "$@" ;;
  esac
  echo "$1" >&2
  exit 1
}
